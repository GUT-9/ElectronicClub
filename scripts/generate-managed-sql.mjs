import { readFile, writeFile } from 'node:fs/promises'

const stripTransaction = (sql) =>
  sql.replace(/^BEGIN;\s*/, '').replace(/\s*COMMIT;\s*$/, '')
const preflight = `-- Existing provider role only. No role creation, elevation or membership changes.
DO $$
DECLARE runtime pg_catalog.pg_roles%ROWTYPE;
BEGIN
 SELECT * INTO runtime FROM pg_roles WHERE rolname='service_role';
 IF NOT FOUND THEN RAISE EXCEPTION 'SERVICE_ROLE_NOT_FOUND'; END IF;
 IF runtime.rolsuper OR runtime.rolcreatedb OR runtime.rolcreaterole OR runtime.rolreplication THEN
  RAISE EXCEPTION 'UNSAFE_SERVICE_ROLE' USING ERRCODE='42501';
 END IF;
 IF EXISTS(SELECT 1 FROM pg_roles r WHERE r.rolname IN ('anon','authenticated') AND
   (pg_has_role(r.oid,runtime.oid,'USAGE') OR pg_has_role(r.oid,current_user,'USAGE'))) THEN
  RAISE EXCEPTION 'PUBLIC_ROLE_INHERITS_PRIVATE_ACCESS' USING ERRCODE='42501';
 END IF;
END $$;
`
const permissions = (
  await readFile('cloudbase/sql/003-permissions.sql', 'utf8')
)
  .split('\n')
  .filter((line) => !line.startsWith('--'))
  .join('\n')
  .replaceAll('electronicclub_api', 'service_role')
const originalRpc = stripTransaction(
  await readFile('cloudbase/sql/004-http-rpc.sql', 'utf8'),
)
const rpc = originalRpc
  .replaceAll('electronicclub_api', 'service_role')
  .replace(
    "NOT pg_has_role(current_user,'service_role','USAGE')",
    "current_user <> 'service_role'",
  )
const managedRpc = rpc.replace(
  /-- If the provider[\s\S]*?(?=NOTIFY pgrst)/,
  '-- Managed mode accepts only the existing service_role, never a schema-owner/browser fallback.\n',
)
const privateRevokes = `-- Remove accidental browser grants only on this application's private objects.
DO $$ DECLARE browser_role text;
BEGIN
 FOR browser_role IN SELECT rolname FROM pg_roles WHERE rolname IN ('anon','authenticated') LOOP
  EXECUTE format('REVOKE ALL ON SCHEMA electronicclub FROM %I',browser_role);
  EXECUTE format('REVOKE ALL ON ALL TABLES IN SCHEMA electronicclub FROM %I',browser_role);
  EXECUTE format('REVOKE ALL ON FUNCTION public.ec_read(text,text),public.ec_list(text,jsonb,integer,integer),public.ec_commit(jsonb,jsonb) FROM %I',browser_role);
 END LOOP;
END $$;
`
const header =
  '-- GENERATED by scripts/generate-managed-sql.mjs. Review as application schema owner.\n-- CloudBase managed PG: existing service_role; no CREATE ROLE and no public data access.\n'
const outputs = {
  'cloudbase/sql/006-managed-service-role.sql': `${header}BEGIN;\n${preflight}\n${permissions}\n${managedRpc}\n${privateRevokes}COMMIT;\n`,
  'cloudbase/sql/editor-https-install.sql': `${header}BEGIN;\n${preflight}\n${stripTransaction(await readFile('cloudbase/sql/001-schema.sql', 'utf8'))}\n${stripTransaction(await readFile('cloudbase/sql/002-indexes.sql', 'utf8'))}\n${permissions}\n${managedRpc}\n${privateRevokes}COMMIT;\n`,
}
for (const [file, sql] of Object.entries(outputs)) {
  if (process.argv.includes('--check')) {
    if ((await readFile(file, 'utf8')) !== sql)
      throw new Error(`Regenerate ${file} with npm run sql:generate`)
  } else await writeFile(file, sql)
}
